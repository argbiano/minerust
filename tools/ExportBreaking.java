// Writes src/world/breaking.rs from the vanilla server's own block hardness and fluid states.
//
// Usage (with the 26.3 server jar's bundled jars unpacked into CP_DIR):
//   javac --release 25 -cp 'CP_DIR/*' -d out tools/ExportBreaking.java
//   java -cp "out:CP_DIR/*" ExportBreaking > src/world/breaking.rs

import java.util.ArrayList;
import java.util.List;
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.EmptyBlockGetter;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockState;

public class ExportBreaking {
    // Bootstrap redirects System.out into the logger, so keep the real one.
    static final java.io.PrintStream OUT = System.out;

    public static void main(String[] args) {
        net.minecraft.SharedConstants.tryDetectVersion();
        net.minecraft.server.Bootstrap.bootStrap();
        List<int[]> instant = new ArrayList<>();
        List<int[]> unbreakable = new ArrayList<>();
        List<int[]> waterlogged = new ArrayList<>();
        for (BlockState state : Block.BLOCK_STATE_REGISTRY) {
            int id = Block.getId(state);
            float speed = state.getDestroySpeed(EmptyBlockGetter.INSTANCE, BlockPos.ZERO);
            if (speed == 0.0f && !state.isAir() && state.getFluidState().isEmpty()) add(instant, id);
            if (speed < 0.0f) add(unbreakable, id);
            // Water source held by a block that isn't water itself: seagrass, kelp, waterlogged=true.
            // (Fluid tags aren't loaded without a data pack, so compare the fluid type.)
            boolean liquidBlock = state.getBlock() instanceof net.minecraft.world.level.block.LiquidBlock;
            if (!liquidBlock
                    && state.getFluidState().isSource()
                    && state.getFluidState().getType() == net.minecraft.world.level.material.Fluids.WATER) add(waterlogged, id);
        }
        String version = net.minecraft.SharedConstants.getCurrentVersion().name();
        OUT.println("// Generated by tools/ExportBreaking.java from the " + version + " server; do not edit.");
        OUT.println("// Sorted block-state id ranges (inclusive).");
        OUT.println();
        table("INSTANT_BREAK", "Blocks with hardness 0, which survival players break with one hit.", instant);
        OUT.println();
        table("UNBREAKABLE", "Blocks with negative hardness, which only creative players break.", unbreakable);
        OUT.println();
        table("WATERLOGGED", "Blocks holding a water source (seagrass, kelp, waterlogged=true), which leave water when broken.", waterlogged);
    }

    static void add(List<int[]> ranges, int id) {
        if (!ranges.isEmpty() && ranges.get(ranges.size() - 1)[1] + 1 == id) {
            ranges.get(ranges.size() - 1)[1] = id;
        } else {
            ranges.add(new int[] {id, id});
        }
    }

    static void table(String name, String doc, List<int[]> ranges) {
        OUT.println("/// " + doc);
        OUT.println("pub const " + name + ": &[(u16, u16)] = &[");
        for (int[] r : ranges) OUT.println("    (" + r[0] + ", " + r[1] + "),");
        OUT.println("];");
    }
}
