"""Writes src/world/passable.rs from a 26.3 data generator blocks.json report.

Usage: python3 tools/export_passable.py generated/reports/blocks.json > src/world/passable.rs

Both tables are name heuristics, not vanilla's collision shapes or fluid rules:
- PASSABLE: blocks without a collision box that mobs walk through (plants, liquids,
  torches, rails...).
- FLUID_REPLACEABLE: blocks that flowing water or lava washes away (air, plants, torches,
  rails, redstone dust, fire, snow layers).
"""
import json
import re
import sys

PASSABLE = re.compile(
    r"^minecraft:("
    r"(void_|cave_)?air|water|lava|bubble_column|light|structure_void"
    r"|(short_|tall_)?grass|(large_)?fern|dead_bush|bush|(short_|tall_)?dry_grass|firefly_bush|leaf_litter|wildflowers|pink_petals"
    r"|.*_sapling|dandelion|poppy|blue_orchid|allium|azure_bluet|.*_tulip|oxeye_daisy|cornflower|lily_of_the_valley"
    r"|wither_rose|torchflower|sunflower|lilac|rose_bush|peony|pitcher_plant|open_eyeblossom|closed_eyeblossom|cactus_flower"
    r"|.*mushroom|crimson_fungus|warped_fungus|crimson_roots|warped_roots|nether_sprouts|twisting_vines(_plant)?|weeping_vines(_plant)?"
    r"|wheat|carrots|potatoes|beetroots|melon_stem|pumpkin_stem|attached_.*_stem|sweet_berry_bush|torchflower_crop|pitcher_crop|nether_wart"
    r"|sugar_cane|kelp(_plant)?|seagrass|tall_seagrass|vine|glow_lichen|sculk_vein|hanging_roots|spore_blossom|cave_vines(_plant)?"
    r"|.*torch|.*wall_torch|fire|soul_fire|nether_portal|end_portal|end_gateway|redstone_wire|tripwire|tripwire_hook|lever"
    r"|.*_button|.*_pressure_plate|.*rail|.*_sign|.*_wall_sign|.*_banner|.*_wall_banner|cobweb|snow|.*coral_fan|.*coral_wall_fan|.*coral"
    r")$"
)

FLUID_REPLACEABLE = re.compile(
    r"^minecraft:("
    r"(void_|cave_)?air|structure_void"
    r"|(short_|tall_)?grass|(large_)?fern|dead_bush|bush|(short_|tall_)?dry_grass|firefly_bush|leaf_litter|wildflowers|pink_petals"
    r"|.*_sapling|dandelion|poppy|blue_orchid|allium|azure_bluet|.*_tulip|oxeye_daisy|cornflower|lily_of_the_valley"
    r"|wither_rose|torchflower|sunflower|lilac|rose_bush|peony|pitcher_plant|open_eyeblossom|closed_eyeblossom|cactus_flower"
    r"|brown_mushroom|red_mushroom|crimson_fungus|warped_fungus|crimson_roots|warped_roots|nether_sprouts"
    r"|wheat|carrots|potatoes|beetroots|melon_stem|pumpkin_stem|attached_.*_stem|sweet_berry_bush|torchflower_crop|pitcher_crop|nether_wart"
    r"|torch|wall_torch|soul_torch|soul_wall_torch|copper_torch|copper_wall_torch|redstone_torch|redstone_wall_torch"
    r"|fire|soul_fire|redstone_wire|tripwire|rail|powered_rail|detector_rail|activator_rail|snow"
    r")$"
)


def ranges_of(blocks, pattern):
    ids = sorted(s["id"] for name, b in blocks.items() if pattern.match(name) for s in b["states"])
    ranges = []
    for i in ids:
        if ranges and ranges[-1][1] + 1 == i:
            ranges[-1][1] = i
        else:
            ranges.append([i, i])
    return ranges


def table(name, doc, ranges):
    print(f"/// {doc}")
    print(f"pub const {name}: &[(u16, u16)] = &[")
    for a, b in ranges:
        print(f"    ({a}, {b}),")
    print("];")


def main():
    blocks = json.load(open(sys.argv[1]))
    print("// Generated by tools/export_passable.py from the 26.3 blocks.json report; do not edit.")
    print("// Sorted block-state id ranges (inclusive).")
    print()
    table("PASSABLE", "Blocks without a collision box.", ranges_of(blocks, PASSABLE))
    print()
    table("FLUID_REPLACEABLE", "Blocks flowing water and lava wash away.", ranges_of(blocks, FLUID_REPLACEABLE))


main()
