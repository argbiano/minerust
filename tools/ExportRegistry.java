// Writes src/world/registry_data.rs: every block's states, properties, item, drop and tool
// needs, and every item's stack size and the block it places, read from the vanilla
// server's own registries, loot tables and tags.
//
// Usage (with the 26.3 server jar's bundled jars unpacked into CP_DIR):
//   javac --release 25 -cp 'CP_DIR/*' -d out tools/ExportRegistry.java
//   java -cp "out:CP_DIR/*" ExportRegistry > src/world/registry_data.rs
//
// Drops are what a non-silk-touch, non-shears break of the default state gives: the first
// loot entry whose conditions hold, where chance-based and tool-matching conditions count
// as failing, block-state conditions are checked against the default state (or the first
// state that drops anything), and
// counts are constants or the middle of a range.

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.PrintStream;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.StandingAndWallBlockItem;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.properties.Property;

public class ExportRegistry {
    // Bootstrap redirects System.out into the logger, so keep the real one.
    static final PrintStream OUT = System.out;
    static final String[] TOOLS = {"pickaxe", "axe", "shovel", "hoe"};
    static final String[] MATERIALS = {"wooden", "stone", "copper", "iron", "golden", "diamond", "netherite"};

    static final PrintStream ERR = System.err;

    public static void main(String[] args) throws Exception {
        try {
            run();
        } catch (Throwable t) {
            t.printStackTrace(ERR);
            System.exit(1);
        }
    }

    static void run() throws Exception {
        net.minecraft.SharedConstants.tryDetectVersion();
        net.minecraft.server.Bootstrap.bootStrap();
        // Item components (stack sizes) are only bound once the data-driven registries exist.
        var lookup = net.minecraft.data.registries.VanillaRegistries.createWorldLookup();
        for (var pending : BuiltInRegistries.DATA_COMPONENT_INITIALIZERS.build(lookup)) pending.apply();

        List<Set<String>> mineable = new ArrayList<>();
        for (String tool : TOOLS) mineable.add(tag("mineable/" + tool));
        List<Set<String>> incorrect = new ArrayList<>();
        for (String material : MATERIALS) incorrect.add(tag("incorrect_for_" + material + "_tool"));

        String version = net.minecraft.SharedConstants.getCurrentVersion().name();
        OUT.println("// Generated by tools/ExportRegistry.java from the " + version + " server; do not edit.");
        OUT.println();
        OUT.println("use super::registry::{Block, Item, NONE, Prop};");
        OUT.println();
        OUT.println("pub static BLOCKS: &[Block] = &[");
        for (Block block : BuiltInRegistries.BLOCK) {
            String name = BuiltInRegistries.BLOCK.getKey(block).getPath();
            List<BlockState> states = block.getStateDefinition().getPossibleStates();
            int first = Block.getId(states.get(0));
            List<Property<?>> props = new ArrayList<>(block.getStateDefinition().getProperties());
            for (BlockState state : states) {
                if (Block.getId(state) != first + index(state, props)) {
                    throw new IllegalStateException("state ids of " + name + " aren't in property order");
                }
            }
            BlockState def = block.defaultBlockState();
            StringBuilder p = new StringBuilder("&[");
            for (Property<?> prop : props) {
                p.append("Prop { name: \"").append(prop.getName()).append("\", values: &[");
                for (Object v : prop.getPossibleValues()) p.append('"').append(valueName(prop, v)).append("\", ");
                p.append("] }, ");
            }
            p.append(']');
            int item = block.asItem() == net.minecraft.world.item.Items.AIR ? -1 : BuiltInRegistries.ITEM.getId(block.asItem());
            // The default state's drop; failing that (a bed's foot drops nothing, its head the
            // bed), the first state that drops something, as breaking either part breaks both.
            int[] drop = new int[] {-1, 0};
            for (BlockState state : withDefaultFirst(def, states)) {
                current = state;
                drop = block.getLootTable().map(k -> {
                    try {
                        return drop(k.identifier().getPath());
                    } catch (Exception ex) {
                        throw new RuntimeException(ex);
                    }
                }).orElse(new int[] {-1, 0});
                if (drop[0] >= 0) break;
            }
            int tools = 0;
            for (int i = 0; i < TOOLS.length; i++) if (mineable.get(i).contains(name)) tools |= 1 << i;
            int bad = 0;
            for (int i = 0; i < MATERIALS.length; i++) if (incorrect.get(i).contains(name)) bad |= 1 << i;
            OUT.println("    Block { name: \"" + name + "\", first: " + first + ", default: " + Block.getId(def)
                + ", props: " + p + ", item: " + id(item) + ", drop: " + id(drop[0]) + ", drop_count: " + drop[1]
                + ", needs_tool: " + def.requiresCorrectToolForDrops() + ", tools: " + tools + ", incorrect: " + bad
                + ", replaceable: " + def.canBeReplaced() + " },");
        }
        OUT.println("];");
        OUT.println();
        OUT.println("pub static ITEMS: &[Item] = &[");
        Field wallBlock = StandingAndWallBlockItem.class.getDeclaredField("wallBlock");
        wallBlock.setAccessible(true);
        for (Item item : BuiltInRegistries.ITEM) {
            String name = BuiltInRegistries.ITEM.getKey(item).getPath();
            int block = -1, wall = -1;
            if (item instanceof BlockItem bi) block = Block.getId(bi.getBlock().defaultBlockState());
            if (item instanceof StandingAndWallBlockItem) {
                wall = Block.getId(((Block) wallBlock.get(item)).defaultBlockState());
            }
            OUT.println("    Item { name: \"" + name + "\", max_stack: " + item.getDefaultMaxStackSize()
                + ", block: " + id(block) + ", wall: " + id(wall) + " },");
        }
        OUT.println("];");
    }

    static List<BlockState> withDefaultFirst(BlockState def, List<BlockState> states) {
        List<BlockState> out = new ArrayList<>(states);
        out.remove(def);
        out.add(0, def);
        return out;
    }

    /** The state block-state loot conditions are checked against. */
    static BlockState current;

    static String id(int v) {
        return v < 0 ? "NONE" : Integer.toString(v);
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    static String valueName(Property prop, Object value) {
        return prop.getName((Comparable) value);
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    static int index(BlockState state, List<Property<?>> props) {
        int index = 0;
        for (Property prop : props) {
            List values = prop.getPossibleValues();
            index = index * values.size() + values.indexOf(state.getValue(prop));
        }
        return index;
    }

    static JsonObject resource(String path) throws Exception {
        try (InputStream in = ExportRegistry.class.getResourceAsStream("/data/minecraft/" + path)) {
            if (in == null) return null;
            return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
        }
    }

    /** Block names in a block tag, following nested tags. */
    static Set<String> tag(String name) throws Exception {
        Set<String> out = new HashSet<>();
        JsonObject json = resource("tags/block/" + name + ".json");
        if (json == null) return out;
        for (JsonElement e : json.getAsJsonArray("values")) {
            String v = e.isJsonObject() ? e.getAsJsonObject().get("id").getAsString() : e.getAsString();
            if (v.startsWith("#")) out.addAll(tag(v.substring(1).replace("minecraft:", "")));
            else out.add(v.replace("minecraft:", ""));
        }
        return out;
    }

    /** [item id, count] of what a block loot table (e.g. "blocks/stone") drops, or [-1, 0]. */
    static int[] drop(String path) throws Exception {
        JsonObject table = resource("loot_table/" + path + ".json");
        if (table == null || !table.has("pools")) return new int[] {-1, 0};
        for (JsonElement pool : table.getAsJsonArray("pools")) {
            JsonObject p = pool.getAsJsonObject();
            if (!conditions(p)) continue;
            for (JsonElement entry : p.getAsJsonArray("entries")) {
                int[] r = entry(entry.getAsJsonObject());
                if (r[0] >= 0) return r;
            }
        }
        return new int[] {-1, 0};
    }

    static int[] entry(JsonObject e) throws Exception {
        if (!conditions(e)) return new int[] {-1, 0};
        String type = e.get("type").getAsString().replace("minecraft:", "");
        switch (type) {
            case "item": {
                String name = e.get("name").getAsString().replace("minecraft:", "");
                Item item = BuiltInRegistries.ITEM.getValue(net.minecraft.resources.Identifier.withDefaultNamespace(name));
                return new int[] {BuiltInRegistries.ITEM.getId(item), count(e)};
            }
            case "alternatives":
            case "group":
            case "sequence":
                for (JsonElement child : e.getAsJsonArray("children")) {
                    int[] r = entry(child.getAsJsonObject());
                    if (r[0] >= 0) return r;
                }
                return new int[] {-1, 0};
            default:
                return new int[] {-1, 0};
        }
    }

    static int count(JsonObject entry) throws Exception {
        int count = 1;
        // 26.3 calls loot functions "modifier"; older formats used "functions".
        JsonElement fns = entry.has("modifier") ? entry.get("modifier") : entry.get("functions");
        if (fns == null) return count;
        for (JsonElement f : fns.isJsonArray() ? fns.getAsJsonArray() : single(fns)) {
            JsonObject fn = f.getAsJsonObject();
            JsonElement kind = fn.has("type") ? fn.get("type") : fn.get("function");
            if (!kind.getAsString().endsWith("set_count") || !conditions(fn)) continue;
            JsonElement c = fn.get("count");
            int n;
            if (c.isJsonPrimitive()) {
                n = (int) c.getAsFloat();
            } else {
                JsonObject o = c.getAsJsonObject();
                if (o.has("min") && o.has("max") && o.get("min").isJsonPrimitive() && o.get("max").isJsonPrimitive()) {
                    n = (int) ((o.get("min").getAsFloat() + o.get("max").getAsFloat()) / 2);
                } else {
                    continue;
                }
            }
            count = fn.has("add") && fn.get("add").getAsBoolean() ? count + n : n;
        }
        return Math.max(count, 1);
    }

    static JsonArray single(JsonElement e) {
        JsonArray a = new JsonArray();
        a.add(e);
        return a;
    }

    /** Whether an entry's, pool's or modifier's condition holds ("condition" in 26.3, "conditions" before). */
    static boolean conditions(JsonObject o) throws Exception {
        JsonElement c = o.has("condition") ? o.get("condition") : o.get("conditions");
        return c == null || condition(c);
    }

    /** A condition: a predicate reference, an inline predicate, or a list that must all hold. */
    static boolean condition(JsonElement e) throws Exception {
        if (e.isJsonArray()) {
            for (JsonElement t : e.getAsJsonArray()) if (!condition(t)) return false;
            return true;
        }
        if (e.isJsonPrimitive()) {
            JsonObject predicate = resource("predicate/" + e.getAsString().replace("minecraft:", "") + ".json");
            return predicate != null && condition(predicate);
        }
        JsonObject c = e.getAsJsonObject();
        JsonElement kind = c.has("type") ? c.get("type") : c.get("condition");
        switch (kind.getAsString().replace("minecraft:", "")) {
            case "survives_explosion":
                return true;
            case "inverted":
                return !condition(c.get("term"));
            case "any_of": {
                for (JsonElement t : c.getAsJsonArray("terms")) if (condition(t)) return true;
                return false;
            }
            case "all_of":
                return condition(c.get("terms"));
            case "match_block":
            case "block_state_property":
                return matchesState(c.get("state"));
            default:
                // match_tool (silk touch, shears), random chances, locations.
                return false;
        }
    }

    /** Whether the default state has the given property values (as for a door's lower half). */
    @SuppressWarnings({"unchecked", "rawtypes"})
    static boolean matchesState(JsonElement state) {
        if (state == null) return true;
        for (var e : state.getAsJsonObject().entrySet()) {
            if (!e.getValue().isJsonPrimitive()) return false;
            Property prop = current.getBlock().getStateDefinition().getProperty(e.getKey());
            if (prop == null || !prop.getName(current.getValue(prop)).equals(e.getValue().getAsString())) return false;
        }
        return true;
    }
}
